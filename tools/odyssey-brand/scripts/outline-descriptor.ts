/**
 * Outlines the descriptor text (Poppins Medium 500, sentence case, tracking 0) to path data
 * so exports and components never depend on a live font.
 * Writes src/brand/descriptorPaths.generated.ts. Run: npm run outline
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';
import { DESCRIPTORS, TYPE } from '../../../lib/brand/odyssey/brandTokens';

const require = createRequire(__filename);
const fontFile = require.resolve(`@fontsource/poppins/files/poppins-latin-${TYPE.descriptor.weight}-normal.woff`);
const buf = readFileSync(fontFile);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const upm = font.unitsPerEm;
const os2 = font.tables.os2 as unknown as { sCapHeight: number };
const r = (n: number) => Math.round(n * 100) / 100;

const glyphs = DESCRIPTORS.map((text) => {
  // Size = unitsPerEm, so path units = font units. Baseline at y = 0, y grows downward.
  const path = font.getPath(text, 0, 0, upm, { kerning: true, letterSpacing: 0 });
  path.commands.forEach((c) => {
    for (const k of ['x', 'y', 'x1', 'y1', 'x2', 'y2'] as const) {
      if (k in c) (c as unknown as Record<string, number>)[k] = r((c as unknown as Record<string, number>)[k]);
    }
  });
  const bb = path.getBoundingBox();
  return {
    text,
    d: path.toPathData(2),
    advance: r(font.getAdvanceWidth(text, upm, { kerning: true })),
    bbox: { x1: r(bb.x1), y1: r(bb.y1), x2: r(bb.x2), y2: r(bb.y2) },
  };
});

const out = `/* eslint-disable */
// GENERATED by scripts/outline-descriptor.ts from ${TYPE.descriptor.family} ${TYPE.descriptor.weight}
// (@fontsource/poppins, SIL OFL). Do not edit. Units: font units, baseline y = 0, y down.
// STATUS: PROPOSED (descriptor wording: CONFIRM)

export const DESCRIPTOR_FONT = {
  family: ${JSON.stringify(TYPE.descriptor.family)},
  weight: ${TYPE.descriptor.weight},
  unitsPerEm: ${upm},
  capHeight: ${os2.sCapHeight},
} as const;

export const DESCRIPTOR_OUTLINES = {
${glyphs
  .map(
    (g) => `  ${JSON.stringify(g.text)}: {
    d: ${JSON.stringify(g.d)},
    advance: ${g.advance},
    bbox: { x1: ${g.bbox.x1}, y1: ${g.bbox.y1}, x2: ${g.bbox.x2}, y2: ${g.bbox.y2} },
  },`,
  )
  .join('\n')}
} as const;
`;
writeFileSync('../../lib/brand/odyssey/descriptorPaths.generated.ts', out);
console.log(`unitsPerEm ${upm}, capHeight ${os2.sCapHeight}`);
glyphs.forEach((g) => console.log(g.text, g.bbox, 'advance', g.advance));
